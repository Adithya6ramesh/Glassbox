// Dev-time generator: Unicode UTS #39 confusables.txt → src/canon/confusables.generated.ts.
// Usage: node scripts/gen-confusables.mjs <path to confusables.txt>
// Pinned: Unicode 16.0.0. The SHA-256 is checked so a changed file can't slip in.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const PINNED_SHA256 = "95bd0aad6dced5ebc63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611";
const file = process.argv[2];
const raw = readFileSync(file);
const sha = createHash("sha256").update(raw).digest("hex");
if (sha !== PINNED_SHA256) throw new Error(`confusables.txt SHA-256 mismatch: ${sha}`);

// Keep mappings whose target is printable ASCII: the lookalikes that matter for
// matching English instruction phrases. ASCII sources are kept too (e.g. "0" → "O"),
// because rule phrases are skeletonized the same way.
const map = {};
for (const line of raw.toString("utf8").split("\n")) {
  const m = /^([0-9A-F]+)\s*;\s*([0-9A-F ]+?)\s*;\s*MA/.exec(line);
  if (!m) continue;
  const src = parseInt(m[1], 16);
  const target = m[2].split(" ").map((h) => String.fromCodePoint(parseInt(h, 16))).join("");
  if (!/^[\x20-\x7e]+$/.test(target)) continue;
  map[src.toString(36)] = target;
}
const out = `// GENERATED by scripts/gen-confusables.mjs from Unicode 16.0.0 confusables.txt
// (SHA-256 ${PINNED_SHA256}). Do not edit by hand.
// Keys: source code point in base 36. Values: ASCII skeleton target.
export const UNICODE_VERSION = "16.0.0";
export const CONFUSABLES: Readonly<Record<string, string>> = ${JSON.stringify(map)};
`;
writeFileSync(new URL("../src/canon/confusables.generated.ts", import.meta.url), out);
console.log(`wrote ${Object.keys(map).length} mappings`);
