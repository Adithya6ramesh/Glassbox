// Builds the embedded baseline ruleset from rules/*.json:
//   packages/engine/src/ruleset/baseline.generated.ts        rules (no test cases) as one JSON string + its SHA-256
//   packages/engine/src/ruleset/baseline-tests.generated.ts  each rule's test cases (used by CI self-tests, I6)
// Splitting keeps the hook's start-up cost low: the engine hashes one small string at load.
// Usage: node packages/rules-baseline/scripts/build.mjs [--check]
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const here = (p) => new URL(p, import.meta.url);
const declarative = JSON.parse(readFileSync(here("../rules/declarative.json"), "utf8"));
const structural = JSON.parse(readFileSync(here("../rules/structural.json"), "utf8"));
const meta = JSON.parse(readFileSync(here("../rules/ruleset.json"), "utf8"));

function input(as, s) {
  const tool = (extra) => ({ name: "probe_tool", description: "Probe tool.", inputSchema: { type: "object" }, ...extra });
  switch (as) {
    case "tool.description": return { surface: "manifest", input: { tools: [tool({ description: s })] } };
    case "schema.description": return { surface: "manifest", input: { tools: [tool({ inputSchema: { type: "object", properties: { x: { type: "string", description: s } } } })] } };
    case "result.text": return { surface: "result", input: { call: { serverId: "probe", toolName: "fetch_page", arguments: {} }, result: { content: [{ type: "text", text: s }] } } };
    case "call.arg": return { surface: "call", input: { serverId: "probe", toolName: "save_note", arguments: { text: s } } };
    case "srvreq.sampling": return { surface: "server-request", input: { serverId: "probe", message: { jsonrpc: "2.0", id: 1, method: "sampling/createMessage", params: { messages: [{ role: "user", content: { type: "text", text: s } }], maxTokens: 10 } } } };
    case "srvreq.elicitation": return { surface: "server-request", input: { serverId: "probe", message: { jsonrpc: "2.0", id: 1, method: "elicitation/create", params: { message: s, requestedSchema: { type: "object", properties: { answer: { type: "string" } } } } } } };
    default: throw new Error(`unknown 'as': ${as}`);
  }
}

const expandRoles = (r) => (r === "@manifestText" ? declarative.manifestText : r.flatMap((x) => (x === "@manifestText" ? declarative.manifestText : [x])));
const EMPTY = { positive: [], negative: [] };
const rules = [];
const tests = {};
for (const r of declarative.rules) {
  rules.push({
    id: r.id, revision: 1, category: r.category, severity: r.severity, confidence: r.confidence, surfaces: r.surfaces,
    target: { roles: expandRoles(r.roles) }, views: r.views, matcher: r.matcher, suppressible: r.suppressible,
    explanation: r.explanation, remediation: r.remediation, testCases: EMPTY,
  });
  tests[r.id] = { positive: r.pos.map((s) => input(r.as, s)), negative: r.neg.map((s) => input(r.as, s)) };
}
for (const [id, category, severity, confidence, surfaces, suppressible, check, explanation, remediation] of structural.rules) {
  rules.push({
    id, revision: 1, category, severity, confidence, surfaces, target: {}, views: ["original"], matcher: { type: "structural", check },
    escalation: false, suppressible, explanation, remediation, testCases: EMPTY,
  });
}
rules.sort((a, b) => (a.id < b.id ? -1 : 1));

const json = JSON.stringify({ ...meta, rules });
const sha = createHash("sha256").update(json, "utf8").digest("hex");
const outBaseline = `// GENERATED by packages/rules-baseline/scripts/build.mjs from packages/rules-baseline/rules/*.json.
// Do not edit by hand. The engine hashes BASELINE_JSON at load; a mismatch makes the baseline unavailable (R17).
export const BASELINE_SHA256 = ${JSON.stringify(sha)};
export const BASELINE_JSON = ${JSON.stringify(json)};
`;
const outTests = `// GENERATED by packages/rules-baseline/scripts/build.mjs. Do not edit by hand.
// Each declarative baseline rule's own test cases (invariant I6). Fake credentials in these
// cases are written as {{fake:<type>}} placeholders and expanded only at test time.
import type { RuleTestCase } from "../types.js";

export const BASELINE_TEST_CASES: Readonly<Record<string, { positive: readonly RuleTestCase[]; negative: readonly RuleTestCase[] }>> = ${JSON.stringify(tests, null, 1)};
`;
const targets = [[here("../../engine/src/ruleset/baseline.generated.ts"), outBaseline], [here("../../engine/src/ruleset/baseline-tests.generated.ts"), outTests]];
if (process.argv.includes("--check")) {
  for (const [t, out] of targets) {
    if (readFileSync(t, "utf8") !== out) { console.error(`${t.pathname} is out of date: run node packages/rules-baseline/scripts/build.mjs`); process.exit(1); }
  }
  console.log("baseline up to date");
} else {
  for (const [t, out] of targets) writeFileSync(t, out);
  console.log(`wrote ${rules.length} rules (${json.length} bytes), sha256 ${sha}`);
}
